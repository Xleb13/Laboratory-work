import random

# Компьютер загадывает случайное число от 1 to 20
secret_number = random.randint(1, 20)
attempts = 0

print("🎯 Я загадал число от 1 до 20. Попробуй угадать его!")

# Цикл продолжается, пока игрок не угадает
while True:
    # Получаем ответ игрока
    guess = int(input("Введи свой вариант: "))
    attempts += 1  # Увеличиваем счетчик попыток

    # Проверяем ответ
    if guess < secret_number:
        print("📉 Твое число слишком маленькое. Попробуй еще раз!")
    elif guess > secret_number:
        print("📈 Твое число слишком большое. Попробуй еще раз!")
    else:
        print(f"🎉 Поздравляю! Ты угадал число {secret_number} за {attempts} попыток!")
        break  # Выходим из цикла, игра окончена
